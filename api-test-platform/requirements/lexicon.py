"""Phase 16 - 需求文本的规则词表（extract / analyze 共用）。

为什么单独一个文件：
  1. 规则引擎的全部"知识"集中在此，调参只改这里，不动逻辑；
  2. extract.py（提取 BR/AC）和 analyze.py（判歧义）用的是同一套词表，
     分开放会出现"两处不一致"的漂移。
"""
from __future__ import annotations

import re

# 规范性词汇：出现即说明这句话在约束系统行为 -> 业务规则(BR)
RULE_MARKERS = (
    "必须", "应当", "应", "需要", "不能", "不得", "禁止", "不允许",
    "最多", "最少", "至少", "不超过", "上限", "下限", "仅", "只允许",
    "由", "支持", "允许",
)

# 可观察结果：出现即说明这句话能判定通过/失败 -> 验收标准(AC)
OBSERVABLE = (
    "返回", "跳转", "成功", "失败", "显示", "提示", "状态", "响应",
    "锁定", "生成", "变为", "弹出", "进入", "拒绝", "校验",
)

# 数值 + 单位：可判定边界，最强 AC 信号（只判存在与否）
NUMERIC = re.compile(
    r"\d+\s*(?:秒|毫秒|分钟|小时|天|周|月|年|件|个|次|位|条|元|%|px|KB|MB|GB)"
)

# 带捕获组的版本：(数字, 单位)。testpoints 造边界值、analyze 比对冲突都用它，
# 两处共用一份，避免"提取 8 位、比较 7 位"这类不一致。
NUMBER_UNIT = re.compile(
    r"(\d+)\s*(秒|毫秒|分钟|小时|天|周|月|年|件|个|次|位|条|元|%|px|KB|MB|GB)"
)

# 约束方向词：判断一个数值是"下限"还是"上限"
LOWER_BOUND = ("至少", "最少", "不低于")
UPPER_BOUND = ("最多", "上限", "不超过", "不高于")

# 需求质量分析专用：主观形容词（不可判定）、指代不明开头、业务动作、失败场景
SUBJECTIVE = ("快速", "稳定", "简洁", "强大", "便捷", "流畅", "美观", "易用")
PRONOUN_START = ("其", "该", "此", "上述", "相关", "此举")
BUSINESS_ACTION = ("支付", "下单", "生成", "删除", "修改", "提交", "添加", "结算", "退款", "发货")
FAILURE_WORDS = ("失败", "异常", "错误", "超时", "重试", "降级", "回滚", "拒绝", "非法", "取消")
TBD = ("待定", "暂定", "TBD", "待确认")


# 模糊词：出现即说明不可判定 -> AC.testable=False，且是歧义来源
VAGUE = (
    "尽快", "及时", "大约", "大概", "左右", "待定", "适当", "合理",
    "友好", "良好", "高效", "高可用", "良好体验", "若干", "某些", "等等",
)
